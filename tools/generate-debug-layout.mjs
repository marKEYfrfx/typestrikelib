// Generates panorama/layout/custom_game/typestrike_debug.xml from src/lib/ui/debugMenu/layout.ts,
// so the slot counts and ids in the XML always match what DebugMenu expects.
// Usage: npm run build:hud   (or with --check to only verify the file is current)
import * as esbuild from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const bundled = await esbuild.build({
    entryPoints: [join(root, "src/lib/ui/debugMenu/layout.ts")],
    bundle: true,
    format: "esm",
    platform: "neutral",
    write: false,
});
const { DEBUG_LAYOUT: L, DebugIds: id } = await import(
    "data:text/javascript;base64," + Buffer.from(bundled.outputFiles[0].text).toString("base64")
);

const t = (n) => "\t".repeat(n);
const label = (indent, labelId, cls) => `${t(indent)}<Label id="${labelId}" class="${cls}" hittest="false" text="{s:${labelId}}" />`;
const lines = [];
const out = (s) => lines.push(s);

out("<root>");
out(`${t(1)}<styles>`);
out(`${t(2)}<include src="file://{resources}/styles/custom_game/typestrike_debug.css" />`);
out(`${t(1)}</styles>`);
out("");
out(`${t(1)}<!--`);
out(`${t(2)}typestrike debug menu. Generated by tools/generate-debug-layout.mjs from`);
out(`${t(2)}src/lib/ui/debugMenu/layout.ts: change the sizes there and run "npm run build:hud"`);
out(`${t(2)}instead of editing this file. Every Label's text is a dialog variable named like its id,`);
out(`${t(2)}filled in by DebugMenu. Classes it toggles are listed in typestrike_debug.css.`);
out(`${t(1)}-->`);
out(`${t(1)}<Panel id="${id.root}" class="TsdRoot" hittest="false">`);
out(`${t(2)}<Panel id="${id.menu}" class="TsdMenu hidden pos-right" hittest="false">`);

// Header: title, game time, mouse toggle, close
out(`${t(3)}<Panel class="TsdHeader" hittest="false">`);
out(label(4, id.title, "TsdTitle"));
out(label(4, id.time, "TsdTime"));
out(`${t(4)}<Button id="${id.mouse}" class="TsdIconButton TsdMouse">`);
out(label(5, id.mouseLabel, "TsdIconLabel"));
out(`${t(4)}</Button>`);
out(`${t(4)}<Button id="${id.close}" class="TsdIconButton TsdClose">`);
out(`${t(5)}<Label class="TsdIconLabel" hittest="false" text="X" />`);
out(`${t(4)}</Button>`);
out(`${t(3)}</Panel>`);

// Tabs
out(`${t(3)}<Panel id="${id.tabs}" class="TsdTabs" hittest="false">`);
for (let i = 0; i < L.tabs; i++) {
    out(`${t(4)}<Button id="${id.tab(i)}" class="TsdTab hidden">`);
    out(label(5, id.tabLabel(i), "TsdTabLabel"));
    out(`${t(4)}</Button>`);
}
out(`${t(3)}</Panel>`);

// Table: header row, data rows (buttons, so a click selects), empty message
out(`${t(3)}<Panel id="${id.table}" class="TsdTable cols-${L.columns}" hittest="false">`);
out(`${t(4)}<Panel id="${id.head}" class="TsdRow TsdHead" hittest="false">`);
for (let c = 0; c < L.columns; c++) out(label(5, id.headCell(c), `TsdCell TsdHeadCell c${c}`));
out(`${t(4)}</Panel>`);
for (let r = 0; r < L.rows; r++) {
    out(`${t(4)}<Button id="${id.row(r)}" class="TsdRow${r % 2 === 1 ? " odd" : ""} hidden">`);
    for (let c = 0; c < L.columns; c++) out(label(5, id.cell(r, c), `TsdCell c${c}`));
    out(`${t(4)}</Button>`);
}
out(label(4, id.empty, "TsdEmpty hidden"));
out(`${t(3)}</Panel>`);

// Action buttons, in rows
for (let row = 0; row * L.actionsPerRow < L.actions; row++) {
    out(`${t(3)}<Panel id="${id.actionRow(row)}" class="TsdActionRow hidden" hittest="false">`);
    for (let i = row * L.actionsPerRow; i < Math.min(L.actions, (row + 1) * L.actionsPerRow); i++) {
        out(`${t(4)}<Button id="${id.action(i)}" class="TsdAction hidden">`);
        out(label(5, id.actionLabel(i), "TsdActionLabel"));
        out(`${t(4)}</Button>`);
    }
    out(`${t(3)}</Panel>`);
}

// Footer: paging and status
out(`${t(3)}<Panel class="TsdFooter" hittest="false">`);
out(`${t(4)}<Button id="${id.prev}" class="TsdPageButton off">`);
out(`${t(5)}<Label class="TsdIconLabel" hittest="false" text="&lt;" />`);
out(`${t(4)}</Button>`);
out(label(4, id.page, "TsdPage"));
out(`${t(4)}<Button id="${id.next}" class="TsdPageButton off">`);
out(`${t(5)}<Label class="TsdIconLabel" hittest="false" text="&gt;" />`);
out(`${t(4)}</Button>`);
out(label(4, id.status, "TsdStatus"));
out(`${t(3)}</Panel>`);
out(label(3, id.hint, "TsdHint"));

out(`${t(2)}</Panel>`);
out(`${t(1)}</Panel>`);
out("</root>");

const file = join(root, L.layoutFile);
const xml = lines.join("\r\n") + "\r\n";

if (process.argv.includes("--check")) {
    // Used by `npm test`: fail if the XML no longer matches layout.ts.
    const current = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== xml.replace(/\r\n/g, "\n")) {
        console.error(`${L.layoutFile} is out of date with src/lib/ui/debugMenu/layout.ts. Run: npm run build:hud`);
        process.exit(1);
    }
    console.log(`${L.layoutFile} is up to date`);
} else {
    writeFileSync(file, xml);
    console.log(`wrote ${L.layoutFile} (${L.tabs} tabs, ${L.rows} rows x ${L.columns} columns, ${L.actions} actions)`);
}
